import {test,expect} from '@playwright/test'

test('validação, cadastro, login e saída',async({page})=>{
  await page.goto('./')
  await page.getByRole('button',{name:'Acessar conta'}).click()
  await expect(page.getByLabel('E-mail',{exact:true})).toBeFocused()
  await expect(page.getByText('Informe sua senha.')).toBeVisible()
  await page.getByRole('button',{name:'Criar conta'}).click()
  const fill = async(id,value)=>page.locator(`#${id}`).fill(value)
  await fill('name','Ana'); await fill('email','ana@example.com')
  await fill('password','exemplo123'); await fill('confirm','outrovalor')
  await page.getByRole('button',{name:'Cadastrar'}).click()
  await expect(page.getByText('Repita a mesma senha nos dois campos.')).toBeVisible()
  await fill('confirm','exemplo123')
  await page.getByRole('button',{name:'Mostrar senha',exact:true}).click()
  await expect(page.locator('#password')).toHaveAttribute('type','text')
  await page.getByRole('button',{name:'Cadastrar'}).click()
  await expect(page.getByRole('status')).toContainText('Cadastro concluído')
  await fill('password','senhaerrada')
  await page.getByRole('button',{name:'Acessar conta'}).click()
  await expect(page.getByRole('status')).toContainText('incorretos')
  await fill('password','exemplo123')
  await page.getByRole('button',{name:'Acessar conta'}).click()
  await expect(page.getByRole('heading',{name:'Olá, Ana!'})).toBeVisible()
  await page.getByRole('button',{name:'Sair da conta'}).click()
  await expect(page.getByRole('heading',{name:'Boas-vindas'})).toBeVisible()
  expect(await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth)).toBe(true)
})
